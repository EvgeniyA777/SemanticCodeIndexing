(defn facts-from-index
  "Turn an already-read SCIP index into arbitrated shadow facts.

  Test / fixture seam only — production callers use `shadow-facts-for-project`,
  which generates the index with the repo-managed CLI first.

  `opts`:
  - `:project-root` (required) — used to digest the workspace files SCIP covered;
  - `:expected-document-digests` — optional `relative-path` -> `sha256:...` map
    for the stale gate;
  - `:provider-id` / `:provider-version` — evidence provenance overrides."
  [scip-index opts]
  (scip-adapter/facts-from-index
   scip-index
   (merge {:language language
           :provider-id provider-id
           :provider-version provider-version}
          (select-keys opts [:project-root :expected-document-digests
                             :provider-id :provider-version]))))

(defn shadow-facts-for-project
  "Run the repo-managed `scip-typescript` CLI over `root_path`, then normalize,
  gate, and arbitrate its output into shadow facts.

  Returns a map with `:result` one of:
  - `\"ready\"`   — the CLI ran and produced facts (see `facts-from-index`);
  - `\"unavailable\"` — no CLI resolved; `:reason_codes [\"scip_cli_missing\"]`,
    no facts, and the caller should degrade to tree-sitter / regex;
  - `\"failed\"`  — the CLI resolved but the index run errored; `:diagnostics`
    carries the reason and there are no facts.

  This never throws for a missing or failing toolchain and never writes to a
  snapshot."
  [{:keys [root_path expected_document_digests] :as opts}]
  (when-not root_path
    (throw (ex-info "shadow-facts-for-project requires :root_path"
                    {:error_code :missing_root_path})))
  (let [cli (resolve-cli opts)]
    (if-not cli
      (scip-adapter/unavailable-result
       {:provider-id provider-id
        :provider-version provider-version
        :reason-codes ["scip_cli_missing"]
        :message (str "no scip-typescript CLI resolved for " root_path
                      "; degrade to tree-sitter/regex")})
      (let [{:keys [index error]} (run-scip-index! cli root_path)]
        (if error
          (assoc (scip-adapter/failed-result {:provider-id provider-id
                                              :provider-version provider-version
                                              :diagnostic error})
                 :cli {:path cli :version (cli-version cli)})
          (-> (facts-from-index index
                                {:project-root root_path
                                 :expected-document-digests expected_document_digests})
              (assoc :cli {:path cli :version (cli-version cli)})))))))
